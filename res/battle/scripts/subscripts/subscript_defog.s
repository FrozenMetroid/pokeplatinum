#include "macros/btlcmd.inc"


_000:
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_REFLECT_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_LIGHT_SCREEN_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_MIST_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_SAFEGUARD_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_SPIKES_LAYERS, _playMoveAndAnim
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_TOXIC_SPIKES_LAYERS, _playMoveAndAnim
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_REFLECT_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_LIGHT_SCREEN_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_MIST_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_SAFEGUARD_TURNS, _playMoveAndAnim
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_SPIKES_LAYERS, _playMoveAndAnim
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_NOT_ZERO, SIDE_COND_TOXIC_SPIKES_LAYERS, _playMoveAndAnim
    CompareVarToValue OPCODE_FLAG_SET, BTLVAR_SIDE_CONDITIONS_DEFENDER, SIDE_CONDITION_STEALTH_ROCK, _playMoveAndAnim
    CompareVarToValue OPCODE_FLAG_SET, BTLVAR_FIELD_CONDITIONS, FIELD_CONDITION_DEEP_FOG, _playMoveAndAnim
    GoTo _lowerEvasion

_playMoveAndAnim:
    Call BATTLE_SUBSCRIPT_ATTACK_MESSAGE_AND_ANIMATION


_lowerEvasion:
    UpdateVar OPCODE_SET, BTLVAR_SIDE_EFFECT_PARAM, MOVE_SUBSCRIPT_PTR_EVASION_DOWN_1_STAGE
    Call BATTLE_SUBSCRIPT_UPDATE_STAT_STAGE
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_REFLECT_TURNS, _clearLightScreen
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_CLEAR, SIDE_COND_REFLECT_TURNS, _clearLightScreen
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_REFLECT
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearLightScreen:
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_LIGHT_SCREEN_TURNS, _clearMist
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_CLEAR, SIDE_COND_LIGHT_SCREEN_TURNS, _clearMist
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_LIGHT_SCREEN
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearMist:
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_MIST_TURNS, _clearSafeguard
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_CLEAR, SIDE_COND_MIST_TURNS, _clearSafeguard
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_MIST
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearSafeguard:
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_SAFEGUARD_TURNS, _clearSpikes
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_CLEAR, SIDE_COND_SAFEGUARD_TURNS, _clearSpikes
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_SAFEGUARD
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearSpikes:
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_SPIKES_LAYERS, _clearPlayerSpikes
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_CLEAR, SIDE_COND_SPIKES_LAYERS, _clearPlayerSpikes
    UpdateVar OPCODE_FLAG_OFF, BTLVAR_SIDE_CONDITIONS_DEFENDER, SIDE_CONDITION_SPIKES
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_SPIKES
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearPlayerSpikes:
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_SPIKES_LAYERS, _clearToxicSpikes
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_CLEAR, SIDE_COND_SPIKES_LAYERS, _clearToxicSpikes
    UpdateVar OPCODE_FLAG_OFF, BTLVAR_SIDE_CONDITIONS_ATTACKER, SIDE_CONDITION_SPIKES
    // if the message has already been printed, do not print it again
    CompareVarToValue OPCODE_EQU, BTLVAR_MSG_MOVE_TEMP, MOVE_SPIKES, _clearToxicSpikes
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_SPIKES
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearToxicSpikes:
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_TOXIC_SPIKES_LAYERS, _clearPlayerToxicSpikes
    CheckSideCondition BTLSCR_DEFENDER, CHECK_SIDE_COND_CLEAR, SIDE_COND_TOXIC_SPIKES_LAYERS, _clearPlayerToxicSpikes
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_TOXIC_SPIKES
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearPlayerToxicSpikes:
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_VAL_ZERO, SIDE_COND_TOXIC_SPIKES_LAYERS, _clearStealthRock
    CheckSideCondition BTLSCR_ATTACKER, CHECK_SIDE_COND_CLEAR, SIDE_COND_TOXIC_SPIKES_LAYERS, _clearStealthRock
    CompareVarToValue OPCODE_EQU, BTLVAR_MSG_MOVE_TEMP, MOVE_TOXIC_SPIKES, _clearStealthRock
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_TOXIC_SPIKES
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearStealthRock:
    CompareVarToValue OPCODE_FLAG_NOT, BTLVAR_SIDE_CONDITIONS_DEFENDER, 0x80, _clearPlayerStealthRock
    UpdateVar OPCODE_FLAG_OFF, BTLVAR_SIDE_CONDITIONS_DEFENDER, 0x80
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_STEALTH_ROCK
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearPlayerStealthRock:
    CompareVarToValue OPCODE_FLAG_NOT, BTLVAR_SIDE_CONDITIONS_ATTACKER, 0x80, _clearFog
    UpdateVar OPCODE_FLAG_OFF, BTLVAR_SIDE_CONDITIONS_ATTACKER, 0x80
    CompareVarToValue OPCODE_EQU, BTLVAR_MSG_MOVE_TEMP, MOVE_STEALTH_ROCK, _clearFog
    UpdateVar OPCODE_SET, BTLVAR_MSG_MOVE_TEMP, MOVE_STEALTH_ROCK
    Call BATTLE_SUBSCRIPT_DEFOG_MESSAGE

_clearFog:
    CompareVarToValue OPCODE_FLAG_NOT, BTLVAR_FIELD_CONDITIONS, FIELD_CONDITION_DEEP_FOG, _End
    UpdateVar OPCODE_FLAG_OFF, BTLVAR_FIELD_CONDITIONS, FIELD_CONDITION_DEEP_FOG
    // {0} blew away the deep fog with {1}!
    PrintMessage BattleStrings_Text_PokemonBlewAwayTheDeepFogWithMove_Ally, TAG_NICKNAME_MOVE, BTLSCR_ATTACKER, BTLSCR_ATTACKER
    Wait 
    WaitButtonABTime 30

_End:
    End 
